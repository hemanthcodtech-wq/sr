// @desc    Get all coupons for Admin management
// @route   GET /api/coupons/admin/all
// @access  Private (Admin)
exports.getAllCouponsAdmin = async (req, res, next) => {
  try {
    const { search = '', type = 'all' } = req.query;

    let query = {};

    if (type === 'admin') {
      query.isReferralReward = false;
    } else if (type === 'referral') {
      query.isReferralReward = true;
    } else if (type === 'active') {
      query.isActive = { $ne: false };
      query.isUsed = false;
      query.expiresAt = { $gt: new Date() };
    } else if (type === 'expired') {
      query.$or = [{ isActive: false }, { isUsed: true }, { expiresAt: { $lte: new Date() } }];
    }

    if (search.trim()) {
      const regex = new RegExp(search.trim(), 'i');
      query.$or = [{ code: regex }, { description: regex }, { badge: regex }];
    }

    let coupons = [];
    if (mongoose.connection.readyState === 1) {
      coupons = await Coupon.find(query)
        .populate('assignedTo', 'name email phone role')
        .populate('referredUser', 'name email')
        .populate('createdBy', 'name email')
        .sort({ createdAt: -1 })
        .lean();
    } else {
      coupons = STARTER_ADMIN_COUPONS;
    }

    // Compute KPI counts
    let totalCount = 0;
    let activeCount = 0;
    let adminCount = 0;
    let referralCount = 0;
    let usedCount = 0;

    if (mongoose.connection.readyState === 1) {
      totalCount = await Coupon.countDocuments();
      activeCount = await Coupon.countDocuments({
        isActive: { $ne: false },
        isUsed: false,
        expiresAt: { $gt: new Date() },
      });
      adminCount = await Coupon.countDocuments({ isReferralReward: false });
      referralCount = await Coupon.countDocuments({ isReferralReward: true });
      usedCount = await Coupon.countDocuments({ isUsed: true });
    }

    res.status(200).json({
      success: true,
      count: coupons.length,
      coupons,
      metrics: {
        total: totalCount || coupons.length,
        active: activeCount,
        adminGenerated: adminCount,
        referralRewards: referralCount,
        totalUsed: usedCount,
      },
    });
  } catch (err) {
    next(err);
  }
};

// @desc    Admin generate / create new coupon
// @route   POST /api/coupons/admin/create
// @access  Private (Admin)
exports.createAdminCoupon = async (req, res, next) => {
  try {
    const {
      code,
      discountType = 'flat',
      discountAmount,
      minOrderAmount = 0,
      maxDiscountAmount = null,
      description = '',
      badge = 'Admin Promo',
      targetType = 'public', // 'public' | 'customer'
      targetEmail = '',
      expiresInDays = 30,
      usageLimit = null,
    } = req.body;

    if (!discountAmount || Number(discountAmount) <= 0) {
      return res.status(400).json({ success: false, message: 'Please specify a valid discount amount' });
    }

    // Auto-generate code if not provided
    let finalCode = (code || '').trim().toUpperCase();
    if (!finalCode) {
      const prefix = discountType === 'percent' ? `SAVE${discountAmount}` : `FLAT${discountAmount}`;
      const randomStr = Math.random().toString(36).substring(2, 6).toUpperCase();
      finalCode = `${prefix}-${randomStr}`;
    }

    // Check code uniqueness
    if (mongoose.connection.readyState === 1) {
      const exists = await Coupon.findOne({ code: finalCode });
      if (exists) {
        return res.status(400).json({ success: false, message: `Coupon with code "${finalCode}" already exists` });
      }
    }

    let assignedTo = null;
    if (targetType === 'customer' && targetEmail.trim()) {
      const targetUser = await User.findOne({ email: targetEmail.trim().toLowerCase() });
      if (!targetUser) {
        return res.status(404).json({ success: false, message: `No customer found with email ${targetEmail}` });
      }
      assignedTo = targetUser._id;
    }

    const expiryDate = new Date(Date.now() + Number(expiresInDays || 30) * 86400000);

    const newCoupon = await Coupon.create({
      code: finalCode,
      discountType,
      discountAmount: Number(discountAmount),
      minOrderAmount: Number(minOrderAmount || 0),
      maxDiscountAmount: maxDiscountAmount ? Number(maxDiscountAmount) : null,
      description: description.trim() || (discountType === 'percent' ? `${discountAmount}% Discount` : `Flat ₹${discountAmount} OFF`),
      badge: badge.trim() || 'Admin Special',
      assignedTo,
      isReferralReward: false,
      createdBy: req.user._id,
      isActive: true,
      usageLimit: usageLimit ? Number(usageLimit) : null,
      expiresAt: expiryDate,
    });

    res.status(201).json({
      success: true,
      message: `Coupon "${finalCode}" created successfully!`,
      coupon: newCoupon,
    });
  } catch (err) {
    next(err);
  }
};

// @desc    Toggle coupon active / inactive
// @route   PUT /api/coupons/admin/:id/toggle
// @access  Private (Admin)
exports.toggleCouponStatus = async (req, res, next) => {
  try {
    const { id } = req.params;
    const coupon = await Coupon.findById(id);
    if (!coupon) {
      return res.status(404).json({ success: false, message: 'Coupon not found' });
    }

    coupon.isActive = !coupon.isActive;
    await coupon.save();

    res.status(200).json({
      success: true,
      message: `Coupon "${coupon.code}" is now ${coupon.isActive ? 'Active' : 'Inactive'}`,
      isActive: coupon.isActive,
    });
  } catch (err) {
    next(err);
  }
};

// @desc    Delete coupon
// @route   DELETE /api/coupons/admin/:id
// @access  Private (Admin)
exports.deleteAdminCoupon = async (req, res, next) => {
  try {
    const { id } = req.params;
    const coupon = await Coupon.findByIdAndDelete(id);
    if (!coupon) {
      return res.status(404).json({ success: false, message: 'Coupon not found' });
    }

    res.status(200).json({
      success: true,
      message: `Coupon "${coupon.code}" deleted successfully`,
    });
  } catch (err) {
    next(err);
  }
};
