// @desc    Get user's available coupons
//          RULE: Referral coupons are ONLY returned if the user actually earned them by referring a friend!
//                Also returns public promotional coupons generated by Admin.
// @route   GET /api/coupons/my-coupons
// @access  Private (Customer / Vendor)
exports.getMyCoupons = async (req, res, next) => {
  try {
    const userId = req.user?._id;
    let availableCoupons = [];

    if (mongoose.connection.readyState === 1 && userId) {
      // Find:
      // 1. Referral coupons awarded directly to this user (assignedTo: userId)
      // 2. Public coupons created by Admin (assignedTo: null)
      availableCoupons = await Coupon.find({
        $or: [
          { assignedTo: userId, isUsed: false },
          { assignedTo: null, isUsed: false },
        ],
        isActive: { $ne: false },
        expiresAt: { $gt: new Date() },
      })
        .populate('referredUser', 'name email')
        .sort({ isReferralReward: -1, createdAt: -1 })
        .lean();
    } else {
      // Mock mode fallback: only return public starter coupons
      availableCoupons = STARTER_ADMIN_COUPONS.map((c, i) => ({
        _id: `mock_${i}`,
        ...c,
        expiresAt: new Date(Date.now() + 30 * 86400000),
      }));
    }

    res.status(200).json({
      success: true,
      count: availableCoupons.length,
      coupons: availableCoupons,
    });
  } catch (err) {
    next(err);
  }
};

// @desc    Validate coupon code against cart value
// @route   POST /api/coupons/validate
// @access  Public (or Private)
exports.validateCoupon = async (req, res, next) => {
  try {
    const { code, cartTotal = 0 } = req.body;
    if (!code) {
      return res.status(400).json({ success: false, message: 'Please enter a coupon code' });
    }

    const cleanCode = code.trim().toUpperCase();

    let coupon = null;
    if (mongoose.connection.readyState === 1) {
      coupon = await Coupon.findOne({ code: cleanCode });
    } else {
      coupon = STARTER_ADMIN_COUPONS.find((c) => c.code === cleanCode);
    }

    if (!coupon) {
      return res.status(404).json({
        success: false,
        message: `Coupon code "${cleanCode}" does not exist.`,
      });
    }

    if (coupon.isActive === false) {
      return res.status(400).json({
        success: false,
        message: `Coupon "${cleanCode}" is currently inactive.`,
      });
    }

    if (coupon.expiresAt && new Date(coupon.expiresAt) < new Date()) {
      return res.status(400).json({
        success: false,
        message: `Coupon "${cleanCode}" has expired.`,
      });
    }

    if (coupon.isUsed) {
      return res.status(400).json({
        success: false,
        message: `Coupon "${cleanCode}" has already been redeemed.`,
      });
    }

    // If coupon is assigned to a specific customer, verify ownership if authenticated
    if (coupon.assignedTo && req.user && coupon.assignedTo.toString() !== req.user._id.toString()) {
      return res.status(403).json({
        success: false,
        message: `This coupon was earned by another user and cannot be applied to your account.`,
      });
    }

    // Minimum cart value check
    if (cartTotal < (coupon.minOrderAmount || 0)) {
      return res.status(400).json({
        success: false,
        message: `Coupon "${cleanCode}" requires a minimum cart value of ₹${coupon.minOrderAmount.toLocaleString('en-IN')}`,
      });
    }

    // Calculate discount amount
    let discount = 0;
    if (coupon.discountType === 'percent') {
      discount = Math.round((cartTotal * coupon.discountAmount) / 100);
      if (coupon.maxDiscountAmount && discount > coupon.maxDiscountAmount) {
        discount = coupon.maxDiscountAmount;
      }
    } else {
      discount = Math.min(coupon.discountAmount, cartTotal);
    }

    res.status(200).json({
      success: true,
      coupon: {
        _id: coupon._id,
        code: coupon.code,
        discount,
        discountType: coupon.discountType,
        discountAmount: coupon.discountAmount,
        minOrderAmount: coupon.minOrderAmount,
        description: coupon.description,
        badge: coupon.badge,
        isReferralReward: coupon.isReferralReward,
      },
    });
  } catch (err) {
    next(err);
  }
};

// @desc    Get customer referral statistics & earned coupons count
// @route   GET /api/coupons/referral-stats
// @access  Private (Customer)
exports.getReferralStats = async (req, res, next) => {
  try {
    const userId = req.user?._id;
    let friendsReferred = 0;
    let referralCouponsEarned = 0;
    let referralCouponsUsed = 0;
    let referredFriendsList = [];

    if (mongoose.connection.readyState === 1 && userId) {
      // Find actual users referred by this customer
      const friends = await User.find({ referredBy: userId })
        .select('name email createdAt avatar')
        .sort({ createdAt: -1 })
        .lean();

      friendsReferred = friends.length;
      referredFriendsList = friends;

      referralCouponsEarned = await Coupon.countDocuments({
        assignedTo: userId,
        isReferralReward: true,
      });

      referralCouponsUsed = await Coupon.countDocuments({
        assignedTo: userId,
        isReferralReward: true,
        isUsed: true,
      });
    }

    const referralCode = req.user?.referralCode || `CUST-${userId?.toString().slice(-6).toUpperCase()}`;

    res.status(200).json({
      success: true,
      referralCode,
      friendsReferred,
      referralCouponsEarned,
      referralCouponsUsed,
      rewardPerFriend: 200,
      referredFriendsList,
    });
  } catch (err) {
    next(err);
  }
};

